  function houseSign(lagnaIdx, house){ return (lagnaIdx + house - 1) % 12; }
  function houseLord(lagnaIdx, house){ return LAGNA_LORD[houseSign(lagnaIdx, house)]; }
  function planetOf(name, chart){ for (var k in chart.planets){ if (chart.planets[k].name===name || chart.planets[k].ru===name) return chart.planets[k]; } return null; }
  function navamsa(signIdx, deg){ var n = Math.floor(deg/(30/9)); if ([0,3,6,9].indexOf(signIdx)>=0) return (0+n)%12; if ([1,4,7,10].indexOf(signIdx)>=0) return (9+n)%12; return (6+n)%12; }
  function dashamsa(signIdx, deg){ var n = Math.floor(deg/3); return (signIdx%2===0)?(signIdx+n)%12:(signIdx+9+n)%12; }

