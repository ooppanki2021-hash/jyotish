  function lordPlacement(p, domain){
    if (p.house===1) return 'Поскольку хозяин ' + domain + ' стоит в самом 1-м доме (в «вашем» доме), эта тема — <b>ваша личная</b>: вы её решаете собой, а не через других.';
    if (p.house===10) return 'Хозяин ' + domain + ' в 10-м доме («вершина») — эта тема связана с вашей <b>карьерой и положением в обществе</b>: через статус вы раскрываете то, чем управляете.';
    if (p.house===7) return 'Хозяин ' + domain + ' в 7-м доме («партнёрство») — эта тема раскрывается <b>через партнёра и союз</b>: в паре, а не в одиночку.';
    if (p.house===4) return 'Хозяин ' + domain + ' в 4-м доме («дом, семья») — эта тема связана с <b>домом и семьями</b>: у вас она «домашняя».';
    if ([5,11].indexOf(p.house)>=0) return 'Хозяин ' + domain + ' в ' + p.house + '-м доме — эта тема идёт через <b>радость, творчество, друзей и большие цели</b>.';
    if ([6,8,12].indexOf(p.house)>=0) return 'Хозяин ' + domain + ' в ' + p.house + '-м доме — эта тема связана с <b>работой, общими делами и внутренней проработкой</b>: требует усилия и ответственности.';
    return 'Хозяин ' + domain + ' в ' + p.house + '-м доме — связывает её со сферой «'+p.house+'-го дома».';
  }
