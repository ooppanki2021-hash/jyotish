    if (h===3) return 'доход идёт через общение, информацию, письмо, продажу знаний и короткие поездки — «говорящая» и «пишущая» работа.';
    if (h===4) return 'доход связан с домом, семьёй и недвижимостью: семейное дело, своё жильё/офис, работа «из своих корней».';
    if (h===5) return 'доход приходит через творчество, детей, любовь, яркость и риск — важно делать то, что любишь от души.';
