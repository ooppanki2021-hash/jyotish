  function hasAsp(aspList, k1, k2, names){
    for (var i=0;i<aspList.length;i++){
      var x = aspList[i];
      var pair = (x.a===k1 && x.b===k2) || (x.a===k2 && x.b===k1);
      if (!pair) continue;
      if (!names || names.indexOf(x.name)>=0) return true;
    }
    return false;
  }
  function anyAspToII(aspList, k, iiRuler, iiPlanets, names){
    for (var i=0;i<aspList.length;i++){
      var x=aspList[i]; if (x.a!==k && x.b!==k) continue;
      var other = x.a===k ? x.b : x.a;
      if (other!==iiRuler && iiPlanets.indexOf(other)<0) continue;
      if (!names || names.indexOf(x.name)>=0) return true;
    }
    return false;
  }

