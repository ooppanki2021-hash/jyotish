  function planetStrength(k, p, aspList){
    var s = 0;
    if (EXALT[k] === p.sign) s += 3; else if ((EXALT[k]+6)%12 === p.sign) s -= 2; else if (SIGN_LORD[p.sign] === PRU[k]) s += 2;
    if ([1,4,7,10].indexOf(p.house) >= 0) s += 2; else if ([2,5,8,11].indexOf(p.house) >= 0) s += 1;
    if (p.house === 10) s += 1; if (p.house === 2) s += 1;
    for (var i=0;i<aspList.length;i++){
      if (aspList[i].a !== k && aspList[i].b !== k) continue;
      var n = aspList[i].name;
      if (n==='трин') s += 2; else if (n==='секстиль') s += 1; else if (n==='соединение') s += 1; else s -= 1;
    }
    return s;
  }

  function collect(nat){
    var info = {}; var asp = []; var keys = ORDER;
    for (var i=0;i<keys.length;i++) for (var j=i+1;j<keys.length;j++){
      var a=keys[i], b=keys[j];
      var ap = aspectOf(nat.planets[a], nat.planets[b]);
      if (ap.orb <= orbFor(a,b)) asp.push({ a:a, b:b, name:ap.name, orb:ap.orb });
    }
    for (var k=0;k<keys.length;k++){
      var key = keys[k];
      var p = { key:key, name:PRU[key], sign:nat.sign[key], inSign:inSign(nat.sign[key]), house:nat.houses[key], planet:nat.planets[key] };
      p.strength = planetStrength(key, p, asp);
      info[key] = p;
    }
    return { byKey:info, asp:asp, ascSign: nat.ascSign };
  }

